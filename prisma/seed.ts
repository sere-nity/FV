import { PrismaClient } from '@prisma/client';
import { readFileSync } from 'fs';
import { join } from 'path';

const prisma = new PrismaClient();

async function main() {
  const seedData = JSON.parse(
    readFileSync(join(process.cwd(), 'seed', 'data.json'), 'utf-8')
  );

  console.log('🌱 Seeding database...');

  // Create creator
  const creator = await prisma.creator.create({
    data: {
      fanvueUserUuid: seedData.creator.fanvueUserUuid,
      handle: seedData.creator.handle,
      displayName: seedData.creator.displayName,
      voiceNotes: seedData.creator.voiceNotes,
    },
  });
  console.log(`✓ Created creator: ${creator.displayName}`);

  // Create shelf items
  for (const item of seedData.shelfItems) {
    await prisma.shelfItem.create({
      data: {
        creatorId: creator.id,
        type: item.type,
        source: item.source,
        url: item.url || null,
        quoteText: item.quoteText || null,
        title: item.title,
        imageUrl: item.imageUrl || null,
        description: item.description || null,
        embedHtml: item.embedHtml || null,
        tags: item.tags || null,
        creatorNote: item.creatorNote,
        embedding: null, // Would be generated by embedding service
      },
    });
  }
  console.log(`✓ Created ${seedData.shelfItems.length} shelf items`);

  // Create fans and messages
  for (const fanData of seedData.fans) {
    const fan = await prisma.fan.create({
      data: {
        creatorId: creator.id,
        fanvueUserUuid: fanData.fanvueUserUuid,
        displayName: fanData.displayName,
      },
    });

    // Create messages for this fan
    if (fanData.messages && fanData.messages.length > 0) {
      for (const msg of fanData.messages) {
        await prisma.message.create({
          data: {
            fanId: fan.id,
            fanvueMessageUuid: `msg-${fan.id}-${Date.now()}-${Math.random()}`,
            sender: msg.sender,
            text: msg.text,
            sentAt: new Date(msg.sentAt),
          },
        });
      }
      console.log(`✓ Created fan ${fan.displayName} with ${fanData.messages.length} messages`);
    } else {
      console.log(`✓ Created fan ${fan.displayName} (empty chat history)`);
    }
  }

  console.log('✅ Seeding complete!');
}

main()
  .catch((e) => {
    console.error('Error seeding database:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
